// Frozen spline/carrier 808, 48 kHz / 32 mono floats. SDK input in R4.
// Tone/Decay latch on START; MODEL selects the new 808 or provisional 909.
// State: weights[8], segment[5], cubic[32], scratch, filter/age/phase/tag,
// then 201 decoded onset coefficients. SDK owns sixteen independent states.
.SECTION/SW seg_swco;
.GLOBAL sharc_voice_render.;
.EXTERN sharc_909_render.;
.EXTERN field_groups.;
.EXTERN field_body.;
.EXTERN field_control.;
.EXTERN field_coordinate.;
.EXTERN field_tone.;
.EXTERN field_low.;
.EXTERN field_low_poly.;
.EXTERN field_state_base.;
.EXTERN k_zero.;
.EXTERN k_one.;
.EXTERN k_two.;
.EXTERN k_three.;
.EXTERN k_four.;
.EXTERN k_half.;
.EXTERN k_quarter.;
.EXTERN k_negative_quarter.;
.EXTERN k_negative_half.;
.EXTERN k_cycle_scale.;
.EXTERN k_twopi.;
.EXTERN k_sin_c1.;
.EXTERN k_sin_c2.;
.EXTERN k_sin_c3.;
.EXTERN k_sin_c4.;
.EXTERN k_sin_c5.;
.EXTERN k_step_sin.;
.EXTERN k_step_cos.;
.EXTERN k_fade_inverse.;
.EXTERN k_fraction.;
.EXTERN k_sixteen.;
.EXTERN k_inverse_canonical.;
.EXTERN k_canonical.;
.EXTERN phase_step_hi.;
.EXTERN phase_step_lo.;

sharc_voice_render.:
    R4=PASS R4;
    IF EQ JUMP finish;
    I4=R4;
    R14=DM(I4,M5);
    R14=PASS R14;
    IF EQ JUMP finish;
    R0=4;
    R0=R4+R0;
    I4=R0;
    R1=DM(I4,M5);
    R0=0xfffffff0;
    R0=R1 AND R0;
    R0=PASS R0;
    IF NE JUMP silent;
    R0=20;
    R0=R4+R0;
    I4=R0;
    R15=DM(I4,M5);
    R0=1060;
    R1=R1*R0(SSI);
    R0=DM(field_state_base.);
    R0=R0+R1;
    COMP(R0,R15);
    IF NE JUMP silent;
    R0=12;
    R0=R4+R0;
    I4=R0;
    R3=DM(I4,M5);
    R0=0xfffffffe;
    R0=R3 AND R0;
    R0=PASS R0;
    IF NE JUMP silent;
    R0=16;
    R0=R4+R0;
    I4=R0;
    R2=DM(I4,M5);
    R2=PASS R2;
    IF EQ JUMP silent;
    I4=R2;
    R5=DM(I4,M5);
    R0=4;
    R0=R2+R0;
    I4=R0;
    R6=DM(I4,M5);
    R0=20;
    R0=R2+R0;
    I4=R0;
    R7=DM(I4,M5);
    R0=0xffff8000;
    R1=R5 OR R6;
    R1=R1 OR R7;
    R0=R0 AND R1;
    R0=PASS R0;
    IF NE JUMP silent;
    R0=32512;
    COMP(R5,R0);
    IF GT JUMP silent;
    COMP(R6,R0);
    IF GT JUMP silent;
    COMP(R7,R0);
    IF GT JUMP silent;
    R3=PASS R3;
    IF EQ JUMP continued;
    R0=244;
    R0=R15+R0;
    I4=R0;
    R1=16384;
    COMP(R7,R1);
    IF LT JUMP start808;
    R1=2;
    DM(I4,M5)=R1;
    JUMP sharc_909_render.;
start808:
    R1=1;
    DM(I4,M5)=R1;
    // Keep delivered Decay across the Tone helper.
    R0=248;
    R0=R15+R0;
    I4=R0;
    DM(I4,M5)=R6;
    R0=R5;
    CALL tone_pole;
    R1=220;
    R1=R15+R1;
    I4=R1;
    DM(I4,M5)=R0;
    R1=DM(k_one.);
    F0=F1-F0;
    R1=DM(k_inverse_canonical.);
    F0=F0*F1;
    R1=224;
    R1=R15+R1;
    I4=R1;
    DM(I4,M5)=R0;
    R0=248;
    R0=R15+R0;
    I4=R0;
    R0=DM(I4,M5);
    CALL decay_weights;
    // Decode the dense onset only once per hit; the tail stays interval-cached.
    I0=field_body.;
    R0=256;
    R0=R15+R0;
    I2=R0;
    R8=201;
prepare_onset:
    I1=R15;
    R7=8;
    R2=0;
prepare_sum:
    R0=DM(I0,M6);
    R1=DM(I1,M6);
    F0=F0*F1;
    F2=F2+F0;
    R7=R7-1;
    IF NE JUMP prepare_sum;
    DM(I2,M6)=R2;
    R8=R8-1;
    IF NE JUMP prepare_onset;
    R0=32;
    R0=R15+R0;
    I4=R0;
    R0=-1;
    DM(I4,M6)=R0;
    DM(I4,M6)=R0;
    DM(I4,M6)=R0;
    DM(I4,M6)=R0;
    DM(I4,M6)=R0;
    R0=228;
    R0=R15+R0;
    I4=R0;
    R0=0;
    DM(I4,M6)=R0;
    DM(I4,M6)=R0;
    DM(I4,M6)=R0;
    DM(I4,M6)=R0;
continued:
    R0=244;
    R0=R15+R0;
    I4=R0;
    R0=DM(I4,M5);
    R1=2;
    COMP(R0,R1);
    IF EQ JUMP sharc_909_render.;
    R1=1;
    COMP(R0,R1);
    IF NE JUMP silent;
    R0=232;
    R0=R15+R0;
    I4=R0;
    R13=DM(I4,M6);
    R0=DM(I4,M5);
    CALL sine;
    R10=R0;
    R0=236;
    R0=R15+R0;
    I4=R0;
    R0=DM(I4,M5);
    R1=0x40000000;
    R0=R0+R1;
    CALL sine;
    R11=R0;
    R12=32;
sample:
    R0=264000;
    COMP(R13,R0);
    IF GE JUMP expired;
    R0=0;
    R1=180;
    R1=R15+R1;
    I4=R1;
    DM(I4,M6)=R0;
    DM(I4,M5)=R0;
    R0=1440;
    COMP(R13,R0);
    IF GE JUMP body;
    R0=0;
    CALL envelope;
    R1=180;
    R1=R15+R1;
    I4=R1;
    DM(I4,M5)=R0;
body:
    R0=960;
    COMP(R13,R0);
    IF LT JUMP blend;
    R0=1;
    CALL envelope;
    F0=F0*F10;
    F1=F1*F11;
    F0=F0+F1;
    R1=184;
    R1=R15+R1;
    I4=R1;
    DM(I4,M5)=R0;
    R0=2;
    CALL envelope;
    F2=F10*F11;
    F2=F2+F2;
    F3=F11*F11;
    F4=F10*F10;
    F3=F3-F4;
    F0=F0*F2;
    F1=F1*F3;
    F0=F0+F1;
    R1=184;
    R1=R15+R1;
    I4=R1;
    R1=DM(I4,M5);
    F0=F0+F1;
    DM(I4,M5)=R0;
    R0=3;
    CALL envelope;
    R2=DM(k_four.);
    R3=DM(k_three.);
    F4=F10*F10;
    F4=F4*F2;
    F4=F3-F4;
    F4=F4*F10;
    F5=F11*F11;
    F5=F5*F2;
    F5=F5-F3;
    F5=F5*F11;
    F0=F0*F4;
    F1=F1*F5;
    F0=F0+F1;
    R1=184;
    R1=R15+R1;
    I4=R1;
    R1=DM(I4,M5);
    F0=F0+F1;
    DM(I4,M5)=R0;
    R0=4;
    CALL envelope;
    R1=184;
    R1=R15+R1;
    I4=R1;
    R1=DM(I4,M5);
    F0=F0+F1;
    DM(I4,M5)=R0;
blend:
    R0=960;
    R0=R13-R0;
    F0=FLOAT R0;
    R1=DM(k_fade_inverse.);
    F0=F0*F1;
    R1=0;
    COMP(F0,F1);
    IF GE JUMP fade_positive;
    R0=0;
fade_positive:
    R1=DM(k_one.);
    COMP(F0,F1);
    IF LE JUMP fade_bounded;
    R0=R1;
fade_bounded:
    F2=F0*F0;
    F0=F0+F0;
    R1=DM(k_three.);
    F0=F1-F0;
    F2=F2*F0;
    R0=DM(k_one.);
    F0=F0-F2;
    R1=180;
    R1=R15+R1;
    I4=R1;
    R3=DM(I4,M6);
    R4=DM(I4,M5);
    F0=F0*F3;
    F2=F2*F4;
    F0=F0+F2;
    // Transposed relative Tone filter, retaining capture units internally.
    R1=224;
    R1=R15+R1;
    I4=R1;
    R1=DM(I4,M6);
    R2=DM(I4,M5);
    F0=F0*F1;
    F2=F2+F0;
    R3=220;
    R3=R15+R3;
    I4=R3;
    R3=DM(I4,M5);
    F3=F3*F2;
    R4=DM(k_canonical.);
    F0=F0*F4;
    F3=F3-F0;
    R0=228;
    R0=R15+R0;
    I4=R0;
    DM(I4,M5)=R3;
    R0=DM(k_four.);
    F0=F0*F2;
    JUMP write;
expired:
    R0=0;
write:
    I4=R14;
    DM(I4,M5)=R0;
    R0=4;
    R14=R14+R0;
    R0=264000;
    COMP(R13,R0);
    IF GE JUMP next_sample;
    R13=R13+1;
    R0=DM(k_step_cos.);
    R1=DM(k_step_sin.);
    F2=F10*F0;
    F3=F11*F1;
    F2=F2+F3;
    F11=F11*F0;
    F3=F10*F1;
    F11=F11-F3;
    R10=R2;
next_sample:
    R12=R12-1;
    IF NE JUMP sample;
    R0=232;
    R0=R15+R0;
    I4=R0;
    DM(I4,M6)=R13;
    R0=DM(I4,M6);
    R1=DM(I4,M5);
    R2=DM(phase_step_lo.);
    R2=R1+R2;
    R3=0;
    // Unsigned low-word carry, independent of signed COMP.
    R4=0x80000000;
    R5=R2 XOR R4;
    R6=R1 XOR R4;
    COMP(R5,R6);
    IF GE JUMP no_carry;
    R3=1;
no_carry:
    R1=DM(phase_step_hi.);
    R0=R0+R1;
    R0=R0+R3;
    R1=236;
    R1=R15+R1;
    I4=R1;
    DM(I4,M6)=R0;
    DM(I4,M5)=R2;
    JUMP finish;
silent:
    R12=32;
    R0=0;
silent_loop:
    I4=R14;
    DM(I4,M5)=R0;
    R1=4;
    R14=R14+R1;
    R12=R12-1;
    IF NE JUMP silent_loop;
finish:
    I12=DM(M7,I6);
    JUMP(M14,I12)(DB);
    RFRAME;
    NOP;

// Signed phase wraps to [-1/2,1/2). Fold to [-1/4,1/4], Taylor degree 11.
sine:
    F0=FLOAT R0;
    R1=DM(k_cycle_scale.);
    F0=F0*F1;
    R1=DM(k_quarter.);
    COMP(F0,F1);
    IF LE JUMP sine_lower;
    R1=DM(k_half.);
    F0=F1-F0;
sine_lower:
    R1=DM(k_negative_quarter.);
    COMP(F0,F1);
    IF GE JUMP sine_polynomial;
    R1=DM(k_negative_half.);
    F0=F1-F0;
sine_polynomial:
    R1=DM(k_twopi.);
    F0=F0*F1;
    F2=F0*F0;
    R3=DM(k_sin_c5.);
    R1=DM(k_sin_c4.);
    F3=F3*F2;
    F3=F1+F3;
    R1=DM(k_sin_c3.);
    F3=F3*F2;
    F3=F1+F3;
    R1=DM(k_sin_c2.);
    F3=F3*F2;
    F3=F1+F3;
    R1=DM(k_sin_c1.);
    F3=F3*F2;
    F3=F1+F3;
    R1=DM(k_one.);
    F3=F3*F2;
    F3=F1+F3;
    F0=F0*F3;
    RTS;

// Raw control in R0. Piecewise cubic pole, dyadic refinement below CC 1.
tone_pole:
    R1=256;
    COMP(R0,R1);
    IF LT JUMP tone_low;
    R1=-8;
    R2=LSHIFT R0 BY R1;
    R1=255;
    R0=R0 AND R1;
    F0=FLOAT R0;
    R1=DM(k_fraction.);
    F9=F0*F1;
    R0=LSHIFT R2 BY 4;
    R1=field_tone.;
    R0=R0+R1;
    I0=R0;
    JUMP cubic_pole;
tone_low:
    R2=0;
    I0=field_low.;
    R4=DM(I0,M6);
tone_find:
    R5=DM(I0,M6);
    COMP(R0,R5);
    IF LT JUMP tone_found;
    R4=R5;
    R2=R2+1;
    JUMP tone_find;
tone_found:
    R0=R0-R4;
    F9=FLOAT R0;
    R0=R5-R4;
    // Dyadic interval lengths: derive reciprocal exactly by repeated halves.
    R1=DM(k_one.);
tone_inverse:
    R8=-1;
    R0=LSHIFT R0 BY R8;
    R0=PASS R0;
    IF EQ JUMP tone_normalized;
    R3=DM(k_half.);
    F1=F1*F3;
    JUMP tone_inverse;
tone_normalized:
    F9=F9*F1;
    R0=LSHIFT R2 BY 4;
    R1=field_low_poly.;
    R0=R0+R1;
    I0=R0;
cubic_pole:
    R0=DM(I0,M6);
    R1=DM(I0,M6);
    F0=F0*F9;
    F0=F0+F1;
    R1=DM(I0,M6);
    F0=F0*F9;
    F0=F0+F1;
    R1=DM(I0,M5);
    F0=F0*F9;
    F0=F0+F1;
    RTS;

// Native raw Decay -> original 8 shared field weights, without fitting.
decay_weights:
    R1=-8;
    R2=LSHIFT R0 BY R1;
    R1=255;
    R0=R0 AND R1;
    F0=FLOAT R0;
    R1=DM(k_fraction.);
    F0=F0*F1;
    R1=LSHIFT R2 BY 2;
    R3=field_coordinate.;
    R1=R1+R3;
    I0=R1;
    R1=DM(I0,M6);
    R3=127;
    COMP(R2,R3);
    IF EQ JUMP coordinate_maximum;
    R2=DM(I0,M5);
    F2=F2-F1;
    F0=F0*F2;
    F0=F0+F1;
    JUMP coordinate_ready;
coordinate_maximum:
    R0=R1;
coordinate_ready:
    R1=DM(k_sixteen.);
    F0=F0*F1;
    R2=TRUNC F0;
    R1=15;
    COMP(R2,R1);
    IF LE JUMP control_segment;
    R2=15;
control_segment:
    F1=FLOAT R2;
    F9=F0-F1;
    R0=LSHIFT R2 BY 7;
    R1=field_control.;
    R0=R0+R1;
    I0=R0;
    I1=R15;
    R8=8;
control_row:
    R0=DM(I0,M6);
    R1=DM(I0,M6);
    F0=F0*F9;
    F0=F0+F1;
    R1=DM(I0,M6);
    F0=F0*F9;
    F0=F0+F1;
    R1=DM(I0,M6);
    F0=F0*F9;
    F0=F0+F1;
    DM(I1,M6)=R0;
    R8=R8-1;
    IF NE JUMP control_row;
    RTS;

// Group R0 -> one/two envelope values F0/F1; preserves F10/F11, R12..R15.
envelope:
    R1=24;
    R1=R0*R1(SSI);
    R2=field_groups.;
    R1=R1+R2;
    R2=204;
    R2=R15+R2;
    I4=R2;
    DM(I4,M5)=R1;
    I4=R1;
    R2=DM(I4,M6);
    R3=DM(I4,M6);
    R4=DM(I4,M6);
    R5=DM(I4,M6);
    R6=DM(I4,M6);
    R7=DM(I4,M5);
    R5=R15+R5;
    I4=R5;
    R8=DM(I4,M5);
    R9=0;
    COMP(R8,R9);
    IF GE JUMP find_interval;
    R8=0;
find_interval:
    R9=LSHIFT R8 BY 4;
    R9=R9+R2;
    I0=R9;
    R0=DM(I0,M6);
    R1=DM(I0,M5);
    F0=FLOAT R13;
    COMP(F0,F1);
    IF LT JUMP interval_found;
    R8=R8+1;
    JUMP find_interval;
interval_found:
    R0=208;
    R0=R15+R0;
    I4=R0;
    DM(I4,M5)=R9;
    I4=R5;
    R0=DM(I4,M5);
    COMP(R0,R8);
    IF EQ JUMP evaluate;
    DM(I4,M5)=R8;
    R6=R15+R6;
    R0=212;
    R0=R15+R0;
    I4=R0;
    DM(I4,M6)=R6;
    DM(I4,M5)=R4;
    // Onset coefficients are per-voice; other groups combine eight basis rows.
    R0=0;
    COMP(R3,R0);
    IF NE JUMP envelope_features;
    R0=LSHIFT R8 BY 2;
    R1=256;
    R0=R0+R1;
    R0=R15+R0;
    I0=R0;
    R0=188;
    R0=R15+R0;
    I2=R0;
    R0=4;
copy_onset:
    R1=DM(I0,M6);
    DM(I2,M6)=R1;
    R0=R0-1;
    IF NE JUMP copy_onset;
    JUMP transform;
envelope_features:
    R0=LSHIFT R8 BY 5;
    R3=R3+R0;
    R0=248;
    R0=R15+R0;
    I4=R0;
    DM(I4,M5)=R3;
channel_features:
    I0=R3;
    R0=188;
    R0=R15+R0;
    I2=R0;
    R8=4;
feature_row:
    I1=R15;
    R7=8;
    R2=0;
feature_sum:
    R0=DM(I0,M6);
    R1=DM(I1,M6);
    F0=F0*F1;
    F2=F2+F0;
    R7=R7-1;
    IF NE JUMP feature_sum;
    DM(I2,M6)=R2;
    R8=R8-1;
    IF NE JUMP feature_row;
transform:
    R0=208;
    R0=R15+R0;
    I4=R0;
    R0=DM(I4,M5);
    R1=12;
    R0=R0+R1;
    I4=R0;
    R0=DM(I4,M5);
    I0=R0;
    R0=188;
    R0=R15+R0;
    I4=R0;
    R4=DM(I4,M6);
    R5=DM(I4,M6);
    R6=DM(I4,M6);
    R7=DM(I4,M5);
    F4=F4-F7;
    F5=F5-F7;
    F6=F6-F7;
    R0=212;
    R0=R15+R0;
    I4=R0;
    R0=DM(I4,M5);
    I2=R0;
    R8=4;
transform_degree:
    R0=DM(I0,M6);
    R1=DM(I0,M6);
    R2=DM(I0,M6);
    F0=F0*F4;
    F1=F1*F5;
    F2=F2*F6;
    F0=F0+F1;
    F0=F0+F2;
    R1=1;
    COMP(R8,R1);
    IF NE JUMP transformed;
    F0=F0+F7;
transformed:
    DM(I2,M6)=R0;
    R8=R8-1;
    IF NE JUMP transform_degree;
    R0=216;
    R0=R15+R0;
    I4=R0;
    R0=DM(I4,M5);
    R0=R0-1;
    DM(I4,M5)=R0;
    IF EQ JUMP evaluate;
    R0=212;
    R0=R15+R0;
    I4=R0;
    R0=DM(I4,M5);
    R1=16;
    R0=R0+R1;
    DM(I4,M5)=R0;
    R0=204;
    R0=R15+R0;
    I4=R0;
    R0=DM(I4,M5);
    R1=20;
    R0=R0+R1;
    I4=R0;
    R1=DM(I4,M5);
    R0=248;
    R0=R15+R0;
    I4=R0;
    R3=DM(I4,M5);
    R3=R3+R1;
    JUMP channel_features;
evaluate:
    R0=208;
    R0=R15+R0;
    I4=R0;
    R0=DM(I4,M5);
    I0=R0;
    R0=DM(I0,M6);
    R1=DM(I0,M6);
    R1=DM(I0,M5);
    F9=FLOAT R13;
    F9=F9-F0;
    F9=F9*F1;
    R0=204;
    R0=R15+R0;
    I4=R0;
    R0=DM(I4,M5);
    R1=16;
    R0=R0+R1;
    I4=R0;
    R0=DM(I4,M5);
    R0=R15+R0;
    I0=R0;
    R0=DM(I0,M6);
    R1=DM(I0,M6);
    F0=F0*F9;
    F0=F0+F1;
    R1=DM(I0,M6);
