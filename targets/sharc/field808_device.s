// Device-test wrapper only: raw EMUCLK spans and one immutable 32-sample witness.
// Per voice: original 1060 bytes, then calls/last/max/previous-clock/period,
// ready/age/Tone/Decay, 32 floats, captured span and captured period (1232 total).
// The measured interval includes the inner C-frame call/return, not this observer.
.SECTION/SW seg_swco;
.GLOBAL sharc_voice_render.;
.EXTERN field808_render.;
.EXTERN field_state_base.;
sharc_voice_render.:
    R4=PASS R4;
    IF EQ JUMP field808_render.;
    R10=R4;
    I4=R4;
    R2=DM(I4,M6);
    R1=DM(I4,M5);
    R0=0xfffffff0;
    R0=R1 AND R0;
    R0=PASS R0;
    IF NE JUMP field808_render.;
    R0=1232;
    R0=R1*R0(SSI);
    R1=DM(field_state_base.);
    R0=R0+R1;
    R1=20;
    R1=R4+R1;
    I4=R1;
    R3=DM(I4,M5);
    COMP(R0,R3);
    IF NE JUMP field808_render.;
    R0=12;
    R0=R4+R0;
    I4=R0;
    R5=DM(I4,M5);
    R0=0xfffffffe;
    R0=R5 AND R0;
    R0=PASS R0;
    IF NE JUMP field808_render.;
    R0=232;
    R0=R3+R0;
    I4=R0;
    R1=DM(I4,M5);
    R5=PASS R5;
    IF EQ JUMP probe_saved;
    R1=0;
    R0=1080;
    R0=R3+R0;
    I4=R0;
    DM(I4,M5)=R1;
    R0=16;
    R0=R4+R0;
    I4=R0;
    R0=DM(I4,M5);
    R0=PASS R0;
    IF EQ JUMP field808_render.;
    I0=R0;
    R6=DM(I0,M6);
    R7=DM(I0,M5);
    R0=1088;
    R0=R3+R0;
    I4=R0;
    DM(I4,M6)=R6;
    DM(I4,M5)=R7;
probe_saved:
    // Six local words below the SDK frame; the nested frame adds two words.
    DM(I7,M7)=R10;
    DM(I7,M7)=R3;
    DM(I7,M7)=R2;
    DM(I7,M7)=R1;
    DM(I7,M7)=R5;
    R0=EMUCLK;
    DM(I7,M7)=R0;
    R4=R10;
    I12=field808_render.;
    R2=I6;
    I6=I7;
    JUMP(M13,I12)(DB);
    DM(I7,M7)=R2;
    DM(I7,M7)=probe_return-1;
probe_return:
    R0=EMUCLK;
    R1=I6;
    R2=-28;
    R1=R1+R2;
    I4=R1;
    R1=DM(I4,M5);
    R0=R0-R1;
    R2=I6;
    R3=-12;
    R2=R2+R3;
    I4=R2;
    R15=DM(I4,M5);
    R2=1060;
    R2=R15+R2;
    I4=R2;
    R2=DM(I4,M5);
    R2=R2+1;
    DM(I4,M6)=R2;
    DM(I4,M6)=R0;
    R3=DM(I4,M5);
    COMPU(R0,R3);
    IF LE JUMP probe_maximum;
    DM(I4,M5)=R0;
probe_maximum:
    R3=1072;
    R3=R15+R3;
    I4=R3;
    R3=DM(I4,M5);
    DM(I4,M6)=R1;
    R1=R1-R3;
    DM(I4,M5)=R1;
    R3=I6;
    R4=-20;
    R3=R3+R4;
    I4=R3;
    R3=DM(I4,M5);
    R4=1024;
    COMP(R3,R4);
    IF NE JUMP probe_finish;
    R4=I6;
    R5=-16;
    R4=R4+R5;
    I4=R4;
    R4=DM(I4,M5);
    I0=R4;
    R4=1096;
    R4=R15+R4;
    I1=R4;
    R5=32;
probe_copy:
    R6=DM(I0,M6);
    DM(I1,M6)=R6;
    R5=R5-1;
    IF NE JUMP probe_copy;
    DM(I1,M6)=R0;
    DM(I1,M5)=R1;
    R0=1084;
    R0=R15+R0;
    I4=R0;
    DM(I4,M5)=R3;
    R0=1080;
    R0=R15+R0;
    I4=R0;
    R0=1;
    DM(I4,M5)=R0;
probe_finish:
    I12=DM(M7,I6);
    JUMP(M14,I12)(DB);
    RFRAME;
    NOP;
