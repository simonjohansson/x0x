// Author-owned ABI diagnostic, not a kick engine. State is 16 {count,pitch} pairs.
.SECTION/SW callback_code;
.GLOBAL sharc_voice_render.;
sharc_voice_render.:
    I4=R4;
    R8=DM(I4,M5);
    R0=4;
    R1=R4+R0;
    I4=R1;
    R2=DM(I4,M5);
    R1=R1+R0;
    I4=R1;
    R5=DM(I4,M5);
    R1=R1+R0;
    I4=R1;
    R7=DM(I4,M5);
    R1=R1+R0;
    I4=R1;
    R9=DM(I4,M5);
    R3=LSHIFT R2 BY 3;
    R6=0x20092800;
    R3=R3+R6;
    I4=R3;
    R6=DM(I4,M5);
    R0=1;
    R7=R7 AND R0;
    R7=PASS R7;
    IF EQ JUMP continued;
    R6=0;
continued:
    R7=R6+1;
    DM(I4,M5)=R7;
    R0=4;
    R3=R3+R0;
    I4=R3;
    DM(I4,M5)=R5;
    I4=R9;
    R0=DM(I4,M5);
    R0=R0+R6;
    R7=-15;
    F0=FLOAT R0 BY R7;
    R9=32;
    R10=4;
write_sample:
    I4=R8;
    DM(I4,M5)=R0;
    R8=R8+R10;
    R9=R9-1;
    IF NE JUMP write_sample;
    I12=DM(M7,I6);
    JUMP(M14,I12) (DB);
    RFRAME;
    NOP;
