// Frozen phase/envelope 909. Tune, Attack and Decay latch on START.
// Shared 512-byte payload: phase, weights, interval polynomials, control scratch.
// I4 stays at the state base; SDK modifiers M5=0, M6=1 and M7=-1 stay intact.
.SECTION/SW seg_swco;
.GLOBAL sharc_909_render.;
.EXTERN x0x_sine.;
.EXTERN x0x_voice_done.;
.EXTERN field_coordinate.;
.EXTERN k_one.;
.EXTERN k_half.;
.EXTERN k_three.;
.EXTERN k_quarter.;
.EXTERN k_fraction.;
.EXTERN k_sixteen.;
.EXTERN f909_phase.;
.EXTERN f909_control.;
.EXTERN f909_control_gain.;
.EXTERN f909_onset_control.;
.EXTERN f909_onset_gain.;
.EXTERN f909_onset.;
.EXTERN f909_body.;
.EXTERN f909_frames.;
.EXTERN f909_inverse.;
.EXTERN f909_time.;
.EXTERN f909_reciprocal.;
.EXTERN f909_q32.;
.EXTERN f909_inv4096.;
.EXTERN f909_inv96.;
.EXTERN f909_step_hi.;
.EXTERN f909_step_lo.;

sharc_909_render.:
    R0=8;
    R0=R2+R0;
    I0=R0;
    R7=DM(I0,M5);
    R0=0xffff8000;
    R0=R7 AND R0;
    R0=PASS R0;
    IF NE JUMP silent909;
    R0=32512;
    COMP(R7,R0);
    IF GT JUMP silent909;
    I4=R15;
    R3=PASS R3;
    IF EQ JUMP continue909;
    R0=2;
    DM(61,I4)=R0;
    DM(54,I4)=R5;
    DM(55,I4)=R7;
    DM(56,I4)=R6;
    R0=0;
    DM(0,I4)=R0;
    DM(1,I4)=R0;
    DM(2,I4)=R0;
    DM(29,I4)=R0;
    R0=DM(k_one.);
    DM(3,I4)=R0;
    R0=R5;
    CALL coordinate909;
    R1=DM(k_sixteen.);
    F0=F0*F1;
    R8=TRUNC F0;
    R1=15;
    COMP(R8,R1);
    IF LE JUMP phase_cell909;
    R8=15;
phase_cell909:
    F1=FLOAT R8;
    F9=F0-F1;
    R0=48;
    R0=R8*R0(SSI);
    R1=f909_phase.;
    R0=R0+R1;
    I5=R0;
    CALL polynomial909;
    DM(31,I4)=R0;
    CALL polynomial909;
    DM(5,I4)=R0;
    R1=DM(31,I4);
    F0=F0+F1;
    CALL cycles909;
    DM(6,I4)=R0;
    CALL polynomial909;
    DM(4,I4)=R0;
    R0=DM(54,I4);
    R10=8;
    CALL control_basis909;
    DM(52,I4)=R8;
    R0=DM(112,I4);
    DM(48,I4)=R0;
    R0=DM(113,I4);
    DM(49,I4)=R0;
    R0=DM(114,I4);
    DM(50,I4)=R0;
    R0=DM(115,I4);
    DM(51,I4)=R0;
    R0=DM(55,I4);
    R10=8;
    CALL control_basis909;
    DM(53,I4)=R8;
    // Twelve joint onset weights; source quantization scales include gain four.
    I5=R15;
    R0=64;
    R0=R15+R0;
    I5=R0;
    I1=f909_onset_gain.;
    R8=f909_onset_control.;
    R11=12;
onset_rank909:
    R0=DM(52,I4);
    R1=11;
    R0=R0*R1(SSI);
    R1=DM(53,I4);
    R0=R0+R1;
    R0=LSHIFT R0 BY 1;
    R6=R8+R0;
    R0=192;
    R0=R15+R0;
    I2=R0;
    R9=4;
    R7=0;
onset_tune909:
    R3=DM(I2,M6);
    R0=448;
    R0=R15+R0;
    I3=R0;
    R10=4;
onset_attack909:
    R0=R6;
    CALL half909;
    R4=DM(I3,M6);
    F0=F0*F3;
    F0=F0*F4;
    F7=F7+F0;
    R0=2;
    R6=R6+R0;
    R10=R10-1;
    IF NE JUMP onset_attack909;
    R0=14;
    R6=R6+R0;
    R9=R9-1;
    IF NE JUMP onset_tune909;
    R0=DM(I1,M6);
    F7=F7*F0;
    DM(I5,M6)=R7;
    R0=244;
    R8=R8+R0;
    R11=R11-1;
    IF NE JUMP onset_rank909;
    R0=DM(56,I4);
    R10=16;
    CALL control_basis909;
    R0=32;
    R0=R15+R0;
    I5=R0;
    I3=f909_control_gain.;
    R9=f909_control.;
    R11=5;
body_rank909:
    R0=LSHIFT R8 BY 1;
    R6=R9+R0;
    R0=448;
    R0=R15+R0;
    I1=R0;
    R10=4;
    R7=0;
body_weight909:
    R0=R6;
    CALL half909;
    R1=DM(I1,M6);
    F0=F0*F1;
    F7=F7+F0;
    R0=2;
    R6=R6+R0;
    R10=R10-1;
    IF NE JUMP body_weight909;
    R0=DM(I3,M6);
    F7=F7*F0;
    DM(I5,M6)=R7;
    R0=40;
    R9=R9+R0;
    R11=R11-1;
    IF NE JUMP body_rank909;
continue909:
    R13=DM(0,I4);
    R0=96000;
    COMP(R13,R0);
    IF GE JUMP expired_block909;
    R12=32;
sample909:
    R0=96000;
    COMP(R13,R0);
    IF GE JUMP expired909;
    R0=0;
    DM(35,I4)=R0;
    R0=288;
    COMP(R13,R0);
    IF LT JUMP prefix909;
    R0=DM(29,I4);
    COMP(R13,R0);
    IF LT JUMP cached909;
    CALL cache909;
cached909:
    R0=DM(3,I4);
    R1=DM(5,I4);
    F0=F0*F1;
    CALL cycles909;
    R1=DM(6,I4);
    R2=DM(1,I4);
    R1=R1+R2;
    R0=R1-R0;
    DM(31,I4)=R0;
    CALL x0x_sine.;
    R10=R0;
    R0=DM(31,I4);
    R1=0x40000000;
    R0=R0+R1;
    CALL x0x_sine.;
    R11=R0;
    DM(33,I4)=R10;
    DM(34,I4)=R11;
    R0=DM(28,I4);
    R0=R13-R0;
    F9=FLOAT R0;
    R0=DM(30,I4);
    F9=F9*F0;
    R0=256;
    R0=R15+R0;
    I5=R0;
    CALL polynomial909;
    R7=R0;
    R8=5;
harmonic909:
    CALL polynomial909;
    F0=F0*F10;
    F7=F7+F0;
    CALL polynomial909;
    F0=F0*F11;
    F7=F7+F0;
    R0=DM(33,I4);
    R1=DM(34,I4);
    F2=F10*F1;
    F3=F11*F0;
    F2=F2+F3;
    F11=F11*F1;
    F3=F10*F0;
    F11=F11-F3;
    R10=R2;
    R8=R8-1;
    IF NE JUMP harmonic909;
    DM(35,I4)=R7;
prefix909:
    R0=1152;
    COMP(R13,R0);
    IF GE JUMP body_output909;
    CALL onset909;
    DM(36,I4)=R0;
    R0=288;
    R0=R13-R0;
    CALL fade909;
    R1=DM(35,I4);
    F0=F0*F1;
    DM(35,I4)=R0;
    R0=1056;
    R0=R13-R0;
    CALL fade909;
    R1=DM(k_one.);
    F0=F1-F0;
    R1=DM(36,I4);
    F0=F0*F1;
    R1=DM(35,I4);
    F0=F0+F1;
    JUMP write909;
body_output909:
    R0=DM(35,I4);
write909:
    I0=R14;
    DM(I0,M6)=R0;
    R14=I0;
    CALL advance909;
    R13=R13+1;
    JUMP next909;
expired909:
    I0=R14;
    R0=0;
    DM(I0,M6)=R0;
    R14=I0;
next909:
    R12=R12-1;
    IF NE JUMP sample909;
    DM(0,I4)=R13;
    JUMP x0x_voice_done.;
expired_block909:
    R0=0;
    DM(127,I4)=R0;
    JUMP silent909;
silent909:
    R12=32;
    R0=0;
silent_loop909:
    I0=R14;
    DM(I0,M6)=R0;
    R14=I0;
    R12=R12-1;
    IF NE JUMP silent_loop909;
finish909:
    I12=DM(M7,I6);
    JUMP(M14,I12)(DB);
    RFRAME;
    NOP;

// Packed signed elements. Only R0..R2/I0 are scratch.
half909:
    R1=2;
    R2=R0 AND R1;
    R2=LSHIFT R2 BY 3;
    R1=16;
    R2=R1-R2;
    R1=-4;
    R0=R0 AND R1;
    I0=R0;
    R0=DM(I0,M5);
    R0=LSHIFT R0 BY R2;
    R1=-16;
    R0=ASHIFT R0 BY R1;
    F0=FLOAT R0;
    RTS;
byte909:
    R1=3;
    R2=R0 AND R1;
    R2=LSHIFT R2 BY 3;
    R1=24;
    R2=R1-R2;
    R1=-4;
    R0=R0 AND R1;
    I0=R0;
    R0=DM(I0,M5);
    R0=LSHIFT R0 BY R2;
    R1=-24;
    R0=ASHIFT R0 BY R1;
    F0=FLOAT R0;
    RTS;
coordinate909:
    R1=-8;
    R2=LSHIFT R0 BY R1;
    R1=255;
    R0=R0 AND R1;
    F3=FLOAT R0;
    R1=DM(k_fraction.);
    F3=F3*F1;
    R0=LSHIFT R2 BY 2;
    R1=field_coordinate.;
    R0=R0+R1;
    I0=R0;
    R0=DM(I0,M6);
    R1=127;
    COMP(R2,R1);
    IF EQ JUMP coordinate_done909;
    R1=DM(I0,M5);
    F1=F1-F0;
    F1=F1*F3;
    F0=F0+F1;
coordinate_done909:
    RTS;
polynomial909:
    R0=DM(I5,M6);
    R1=DM(I5,M6);
    F0=F0*F9;
    F0=F0+F1;
    R1=DM(I5,M6);
    F0=F0*F9;
    F0=F0+F1;
    R1=DM(I5,M6);
    F0=F0*F9;
    F0=F0+F1;
    RTS;
cycles909:
    R1=TRUNC F0;
    F1=FLOAT R1;
    F0=F0-F1;
    R1=DM(k_half.);
    COMP(F0,F1);
    IF LT JUMP fraction909;
    R1=DM(k_one.);
    F0=F0-F1;
fraction909:
    R1=DM(f909_q32.);
    F0=F0*F1;
    R0=TRUNC F0;
    RTS;
fade909:
    R1=0;
    COMP(R0,R1);
    IF LE JUMP fade_zero909;
    R1=96;
    COMP(R0,R1);
    IF GE JUMP fade_one909;
    F0=FLOAT R0;
    R1=DM(f909_inv96.);
    F0=F0*F1;
    F2=F0*F0;
    F0=F0+F0;
    R1=DM(k_three.);
    F0=F1-F0;
    F0=F0*F2;
    RTS;
fade_zero909:
    R0=0;
    RTS;
fade_one909:
    R0=DM(k_one.);
    RTS;
advance909:
    R0=DM(3,I4);
    R1=DM(4,I4);
    F1=F1*F0;
    F0=F0-F1;
    DM(3,I4)=R0;
    R0=DM(2,I4);
    R1=DM(f909_step_lo.);
    R2=R0+R1;
    R3=0;
    COMPU(R2,R0);
    IF GE JUMP no_carry909;
    R3=1;
no_carry909:
    DM(2,I4)=R2;
    R0=DM(1,I4);
    R1=DM(f909_step_hi.);
    R0=R0+R1;
    R0=R0+R3;
    DM(1,I4)=R0;
    RTS;

// Uniform clamped cubic basis. R0=raw control, R10=interval count.
// R8=cell, N[4] at byte 448. Cox-de Boor denominators are 1, 2 or 3.
control_basis909:
    CALL coordinate909;
    F1=FLOAT R10;
    F0=F0*F1;
    R8=TRUNC F0;
    COMP(R8,R10);
    IF LT JUMP basis_cell909;
    R8=R10-1;
basis_cell909:
    F1=FLOAT R8;
    F9=F0-F1;
    R0=DM(k_one.);
    DM(112,I4)=R0;
    R0=0;
    DM(113,I4)=R0;
    DM(114,I4)=R0;
    DM(115,I4)=R0;
    R11=1;
basis_degree909:
    R0=R11-1;
    COMP(R0,R8);
    IF LE JUMP left909;
    R0=R8;
left909:
    F0=FLOAT R0;
    F0=F0+F9;
    R1=LSHIFT R11 BY 2;
    R2=464;
    R2=R15+R2;
    R1=R1+R2;
    I0=R1;
    DM(I0,M5)=R0;
    R0=R10-R8;
    COMP(R0,R11);
    IF LE JUMP right909;
    R0=R11;
right909:
    F0=FLOAT R0;
    F0=F0-F9;
    R1=LSHIFT R11 BY 2;
    R2=480;
    R2=R15+R2;
    R1=R1+R2;
    I0=R1;
    DM(I0,M5)=R0;
    R6=0;
    R7=0;
basis_inner909:
    R0=LSHIFT R6 BY 2;
    R1=448;
    R1=R15+R1;
    R0=R0+R1;
    I1=R0;
    R0=R11-R6;
    R0=LSHIFT R0 BY 2;
    R1=464;
    R1=R15+R1;
    R0=R0+R1;
    I2=R0;
    R0=R6+1;
    R0=LSHIFT R0 BY 2;
    R1=480;
    R1=R15+R1;
    R0=R0+R1;
    I3=R0;
    R0=DM(I3,M5);
    R1=DM(I2,M5);
    F2=F0+F1;
    R3=DM(k_half.);
    F2=F2+F3;
    R2=TRUNC F2;
    R2=LSHIFT R2 BY 2;
    R3=f909_reciprocal.;
    R2=R2+R3;
    I0=R2;
    R2=DM(I0,M5);
    R3=DM(I1,M5);
    F3=F3*F2;
    F0=F0*F3;
    F0=F0+F7;
    DM(I1,M5)=R0;
    F7=F1*F3;
    R6=R6+1;
    COMP(R6,R11);
    IF LT JUMP basis_inner909;
    R0=LSHIFT R11 BY 2;
    R1=448;
    R1=R15+R1;
    R0=R0+R1;
    I0=R0;
    DM(I0,M5)=R7;
    R11=R11+1;
    R0=4;
    COMP(R11,R0);
    IF LT JUMP basis_degree909;
    RTS;

cache909:
    I0=f909_frames.;
    R0=DM(I0,M6);
    R8=0;
find909:
    R1=DM(I0,M6);
    COMP(R13,R1);
    IF LT JUMP found909;
    R0=R1;
    R8=R8+1;
    JUMP find909;
found909:
    DM(7,I4)=R8;
    DM(28,I4)=R0;
    DM(29,I4)=R1;
    R0=LSHIFT R8 BY 2;
    R1=f909_inverse.;
    R0=R0+R1;
    I0=R0;
    R0=DM(I0,M5);
    DM(30,I4)=R0;
    R0=256;
    R0=R15+R0;
    I5=R0;
    R11=0;
cache_channel909:
    R0=148;
    R0=R15+R0;
    I2=R0;
    R10=0;
cache_node909:
    R0=29;
    R0=R11*R0(SSI);
    R0=R0+R8;
    R0=R0-1;
    R0=R0+R10;
    R0=LSHIFT R0 BY 1;
    R1=f909_body.;
    R5=R0+R1;
    R0=32;
    R0=R15+R0;
    I1=R0;
    R6=5;
    R7=0;
cache_rank909:
    R0=R5;
    CALL half909;
    R3=DM(I1,M6);
    F0=F0*F3;
    F7=F7+F0;
    R0=640;
    R5=R5+R0;
    R6=R6-1;
    IF NE JUMP cache_rank909;
    DM(I2,M6)=R7;
    R10=R10+1;
    R0=4;
    COMP(R10,R0);
    IF LT JUMP cache_node909;
    R4=DM(37,I4);
    R5=DM(38,I4);
    R6=DM(39,I4);
    R7=DM(40,I4);
    F4=F4-F7;
    F5=F5-F7;
    F6=F6-F7;
    R0=DM(f909_inv4096.);
    F4=F4*F0;
    F5=F5*F0;
    F6=F6*F0;
    R0=24;
    R0=R8*R0(SSI);
    R1=f909_time.;
    R0=R0+R1;
    I3=R0;
    R10=0;
cache_degree909:
    R0=I3;
    CALL half909;
    F3=F0*F4;
    R0=I3;
    R1=2;
    R0=R0+R1;
    I3=R0;
    CALL half909;
    F0=F0*F5;
    F3=F3+F0;
    R0=I3;
    R1=2;
    R0=R0+R1;
    I3=R0;
    CALL half909;
    F0=F0*F6;
    F3=F3+F0;
    R0=I3;
    R1=2;
    R0=R0+R1;
    I3=R0;
    R0=3;
    COMP(R10,R0);
    IF NE JUMP cache_store909;
    F3=F3+F7;
cache_store909:
    DM(I5,M6)=R3;
    R10=R10+1;
    R0=4;
    COMP(R10,R0);
    IF LT JUMP cache_degree909;
    R11=R11+1;
    R0=11;
    COMP(R11,R0);
    IF LT JUMP cache_channel909;
    RTS;

onset909:
    R8=R13;
    R9=0;
    R0=320;
    COMP(R8,R0);
    IF LT JUMP onset_node909;
    R8=R8-R0;
    R0=3;
    R0=R8 AND R0;
    F9=FLOAT R0;
    R0=DM(k_quarter.);
    F9=F9*F0;
    R0=-2;
    R8=LSHIFT R8 BY R0;
    R0=320;
    R8=R8+R0;
onset_node909:
    R0=12;
    R0=R8*R0(SSI);
    R1=f909_onset.;
    R0=R0+R1;
    I2=R0;
    R1=12;
    R0=R0+R1;
    I3=R0;
    R0=64;
    R0=R15+R0;
    I1=R0;
    R10=12;
    R6=0;
    R7=0;
onset_sum909:
    R3=DM(I1,M6);
    R0=I2;
    CALL byte909;
    F0=F0*F3;
    F7=F7+F0;
    R0=I3;
    CALL byte909;
    F0=F0*F3;
    F6=F6+F0;
    R0=I2;
    R1=1;
    R0=R0+R1;
    I2=R0;
    R0=I3;
    R0=R0+R1;
    I3=R0;
    R10=R10-1;
    IF NE JUMP onset_sum909;
    F0=F6-F7;
    F0=F0*F9;
    F0=F0+F7;
    RTS;
